/**
 * CryptoShield — Phase 2 crypto engine.
 *
 * This is the boundary between real persisted mail (`/api/emails/*`) and the
 * Web Crypto primitives in `lib/crypto.ts`. Everything here runs in the
 * browser: the server stores ciphertext but never receives a private key or an
 * AES session key.
 *
 *   SEND
 *     1. RSA-OAEP + RSA-PSS identity keys (generated once, at registration)
 *     2. ephemeral AES-256-GCM key → encrypt canonical payload
 *     3. RSA-OAEP wrap the AES key with the recipient's public key
 *     4. RSA-PSS sign the SHA-256 digest with the sender's private key
 *
 *   RECEIVE
 *     1. RSA-OAEP unwrap with the recipient's private key
 *     2. AES-GCM decrypt + authentication-tag check
 *     3. RSA-PSS verify with the sender's DB-registered public key
 *     4. bind the signed sender/recipient/subject metadata to the stored row
 *     5. DOMPurify the recovered HTML before it reaches the renderer
 */

import {
  decryptAndVerify,
  hybridEncrypt,
  jwkFingerprint,
  type StepReporter,
} from "@/lib/crypto";
import {
  generateIdentityKeyMaterial,
  type IdentityPrivateKeys,
} from "@/lib/crypto/identity";
import type {
  DirectoryEntry,
  EmailPayload,
  SecurePayload,
  SenderPublicKeys,
  VerificationResult,
} from "@/lib/types";

/** Key material generated by the browser for a new identity. */
export async function generateIdentity(): Promise<{
  publicKeys: SenderPublicKeys;
  privateKeys: IdentityPrivateKeys;
}> {
  return generateIdentityKeyMaterial();
}

export interface SecurePackage {
  /** Plaintext subject (stored as searchable metadata; covered by the signature). */
  subject: string;
  /** base64(12-byte IV ‖ AES-256-GCM ciphertext) — goes into `Email.body`. */
  ciphertext: string;
  /** base64 RSA-OAEP-wrapped AES-256 key. */
  encryptedSymmetricKey: string;
  /** base64 RSA-PSS-SHA256 signature over the canonical payload. */
  signature: string;
  /** Client clock; bound into the signed payload. */
  timestamp: number;
}

export interface EncryptMessageInput {
  sender: {
    email: string;
    publicKeys: SenderPublicKeys;
    signingPrivateKey: JsonWebKey;
  };
  recipient: {
    email: string;
    publicKeys: SenderPublicKeys;
  };
  subject: string;
  body: string;
  timestamp?: number;
}

/**
 * Encrypt + sign one message for a recipient. The returned `ciphertext` is the
 * only representation of the body that should ever reach the server.
 */
export async function encryptMessage(
  input: EncryptMessageInput,
  report?: StepReporter,
): Promise<SecurePackage> {
  const timestamp = input.timestamp ?? Date.now();
  const payload: SecurePayload = {
    sender: input.sender.email,
    recipient: input.recipient.email,
    subject: input.subject,
    body: input.body,
    timestamp,
  };

  const envelope = await hybridEncrypt(
    payload,
    input.recipient.publicKeys.encryption,
    {
      address: input.sender.email,
      publicKey: input.sender.publicKeys,
      signingPriv: input.sender.signingPrivateKey,
    },
    report,
  );

  return {
    subject: input.subject,
    ciphertext: envelope.payloadCiphertext,
    encryptedSymmetricKey: envelope.encryptedSymmetricKey,
    signature: envelope.signature,
    timestamp,
  };
}

export interface DecryptMessageInput {
  /** Stored message mapped into the engine's EmailPayload shape. */
  message: EmailPayload;
  recipientPrivateKeys: IdentityPrivateKeys;
  /** Sender's public keys as returned by the authenticated inbox API. */
  senderPublicKeys: SenderPublicKeys;
  report?: StepReporter;
}

export interface DecryptMessageResult {
  payload: SecurePayload | null;
  verification: VerificationResult;
  failedStage?: "unwrap" | "decrypt" | "payload";
}

/**
 * Decrypt and authenticate one stored secure message.
 *
 * The sender key comes from PostgreSQL (the inbox response), not from the
 * ciphertext itself. The engine still builds a directory entry from it so the
 * existing binding check runs, but the trust anchor is the authenticated DB
 * row, not client-supplied envelope data.
 */
export async function decryptMessage(
  input: DecryptMessageInput,
): Promise<DecryptMessageResult> {
  const { message, senderPublicKeys } = input;

  if (!message.ciphertext || !message.symmetricKey || !message.signature) {
    return {
      payload: null,
      verification: {
        status: "spoofed-tampered",
        reason: "Stored message is missing its ciphertext, wrapped key or signature.",
      },
      failedStage: "payload",
    };
  }

  let directory: DirectoryEntry;
  try {
    directory = {
      address: message.sender,
      encryptionPub: senderPublicKeys.encryption,
      signingPub: senderPublicKeys.signing,
      fingerprint: await jwkFingerprint(senderPublicKeys.signing),
      source: "browser",
    };
  } catch {
    return {
      payload: null,
      verification: {
        status: "spoofed-unverified",
        reason: `The stored public key for ${message.sender} is unreadable.`,
      },
      failedStage: "payload",
    };
  }

  const outcome = await decryptAndVerify(
    message,
    input.recipientPrivateKeys.encryption,
    directory,
    input.report,
  );

  if (!outcome.payload) return outcome;

  // Never hand unauthenticated plaintext to the renderer: a failed signature or
  // failed key binding means the content is untrusted, even if GCM decrypted it.
  if (outcome.verification.status !== "verified") {
    return { ...outcome, payload: null };
  }

  // The signature authenticates the payload metadata. A row whose sender,
  // recipient or subject was edited in the database must not be presented as
  // verified even though the body ciphertext is intact.
  const metadataMatches =
    outcome.payload.sender.toLowerCase() === message.sender.toLowerCase() &&
    outcome.payload.recipient.toLowerCase() === message.recipient.toLowerCase() &&
    outcome.payload.subject === message.subject;

  if (!metadataMatches) {
    return {
      payload: null,
      verification: {
        status: "spoofed-tampered",
        reason:
          "Signed envelope metadata does not match the stored message (sender, recipient or subject was altered).",
        fingerprint: directory.fingerprint,
      },
      failedStage: "payload",
    };
  }

  return outcome;
}

/** Sanitize recovered HTML with DOMPurify before rendering. Client-only. */
export async function sanitizeDecryptedHtml(html: string): Promise<string> {
  const { sanitizeHtml } = await import("@/lib/sanitize");
  return sanitizeHtml(html);
}

